#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES.md: every Rust crate and npm package that ends up in the app, with its
licence and the licence texts the packages themselves ship.

    python scripts/gen-third-party.py [--target x86_64-pc-windows-msvc]

What counts: the normal (non-build, non-dev) dependency closure of app/src-tauri for the given
target, read with `cargo metadata --offline` (so the registry sources must already be fetched,
which any build does), minus our own crates (GPL-3.0-or-later, see LICENSE). For the web side, the
packages the built frontend contains (@tauri-apps/*, svelte and the SvelteKit runtime) are read
from app/node_modules. Texts are the LICENSE/COPYING/NOTICE files in each package; identical
texts are printed once with the list of packages they belong to. The same file is bundled into the
installer (tauri.conf.json `bundle.resources`) and shown from Settings > About.

Re-run after changing a dependency, and commit the result.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAURI = os.path.join(ROOT, "app", "src-tauri")
NODE = os.path.join(ROOT, "app", "node_modules")
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES.md")
TARGET = "x86_64-pc-windows-msvc"
if "--target" in sys.argv:
    TARGET = sys.argv[sys.argv.index("--target") + 1]

LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|unlicense|notice)([-_. ].*)?$", re.I)

# npm packages whose code is in the built frontend. Versions and licences come from node_modules.
NPM = ["@tauri-apps/api", "@tauri-apps/plugin-dialog", "svelte", "@sveltejs/kit", "esm-env", "clsx", "devalue", "cookie", "set-cookie-parser", "sirv", "mrmime", "magic-string", "aria-query", "axobject-query", "is-reference", "esrap", "acorn", "zimmerframe", "locate-character"]

HEADER = """# Third-party notices

Pacemaker Revival is GPL-3.0-or-later (see `LICENSE`). This file lists the software it contains that is
not ours. It is generated by `scripts/gen-third-party.py` from the dependency tree of this build
(target `{target}`); the licence texts are the ones the packages themselves ship.

## Notes on particular components

| Component | Version | Licence | Used for |
| --- | --- | --- | --- |
| LAME (bundled by `mp3lame-sys`, wrapper `mp3lame-encoder`) | LAME 4.0, mp3lame-sys 0.2.0, mp3lame-encoder 0.3.0 | LGPL-3.0 | Writing MP3 files: stem separation results (`crates/pm-stems`) and exported mixes and their tags (`crates/pm-mixer`) |
| Vorbis encoder (`vorbis_rs`, built on the aoTuV/libvorbis sources) | 0.5.6 | BSD-3-Clause | Writing Ogg Vorbis stem files |
| `rustfft` | 6.4.1 | MIT OR Apache-2.0 | STFT / inverse STFT |
| `ort` (Rust bindings for ONNX Runtime, `load-dynamic`) | 2.0.0-rc.15 | MIT OR Apache-2.0 | Running the model; the ONNX Runtime library itself is loaded at run time, not linked |

LAME is statically linked. LGPL-3.0 asks that a recipient can replace the LAME code and relink: the
complete source of this app is published under GPL-3.0-or-later, so the whole program can be rebuilt with
another LAME. The LAME licence text is in the `mp3lame-sys` crate (`lame-4.0/COPYING`).

### Downloaded by the user, never bundled

These are fetched only after the user accepts the notice shown in the Stems view, from the address in the
manifest, and checked against a pinned SHA-256.

| Component | Licence | Note |
| --- | --- | --- |
| HTDemucs 4-stem model, ONNX Runtime format (third-party conversion on Hugging Face by `gentij`) | Demucs code: MIT. Trained weights: **licence not clear** (the weights' author says so, because the MUSDB18 training data includes research-only material). The conversion has no licence of its own | Not hosted or redistributed by this project. Personal music preparation at the user's own risk; do not assume commercial use is allowed |
| ONNX Runtime (Microsoft), CPU build | MIT (the release zip carries its own third-party notices) | Only the libraries the app needs are unpacked |

See `notes/vocal-isolation-pc.md` for the research behind these choices and what is unverified.
"""


def run_metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--offline", "--format-version", "1", "--filter-platform", TARGET],
        cwd=TAURI, check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


def normal_closure(meta):
    """Package ids reachable from the root through normal dependencies only."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, todo = set(), [meta["resolve"]["root"]]
    while todo:
        pid = todo.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    return seen


def license_files(pkg_dir):
    found = []
    for base, dirs, files in os.walk(pkg_dir):
        depth = os.path.relpath(base, pkg_dir).count(os.sep) + (0 if base == pkg_dir else 1)
        if depth > 2:
            dirs[:] = []
            continue
        dirs[:] = [d for d in dirs if d not in ("target", "node_modules", ".git", "tests", "benches", "examples", "src", "docs")]
        for f in sorted(files):
            if LICENSE_FILE.match(f) or (depth > 0 and LICENSE_FILE.match(os.path.splitext(f)[0])):
                full = os.path.join(base, f)
                if os.path.getsize(full) < 200_000:
                    found.append(full)
    return found


def read_text(path):
    with open(path, "rb") as fh:
        return fh.read().decode("utf-8", "replace").replace("\r\n", "\n").strip("\n")


def main():
    meta = run_metadata()
    ids = normal_closure(meta)
    pkgs = {p["id"]: p for p in meta["packages"]}
    rows = []  # (name, version, license, repository, texts)
    for pid in sorted(ids, key=lambda i: (pkgs[i]["name"], pkgs[i]["version"])):
        p = pkgs[pid]
        if p["source"] is None:  # our own crates (path dependencies)
            continue
        d = os.path.dirname(p["manifest_path"])
        rows.append((p["name"], p["version"], p.get("license") or p.get("license_file") or "see package", p.get("repository") or "", [read_text(f) for f in license_files(d)]))
    for name in NPM:
        pj = os.path.join(NODE, *name.split("/"), "package.json")
        if not os.path.isfile(pj):
            continue
        j = json.load(open(pj, encoding="utf-8"))
        lic = j.get("license") or "see package"
        repo = j.get("repository", "")
        repo = repo.get("url", "") if isinstance(repo, dict) else repo
        rows.append((name + " (npm)", j.get("version", "?"), lic if isinstance(lic, str) else str(lic), repo, [read_text(f) for f in license_files(os.path.dirname(pj))]))

    groups = {}  # text hash -> (text, [names])
    missing = []
    for name, ver, lic, _repo, texts in rows:
        if not texts:
            missing.append(f"{name} {ver}")
        for t in texts:
            h = hashlib.sha256(t.encode()).hexdigest()
            groups.setdefault(h, (t, []))[1].append(f"{name} {ver}")

    out = [HEADER.format(target=TARGET)]
    out.append(f"## Packages ({len(rows)})\n")
    out.append("| Package | Version | Licence |\n| --- | --- | --- |")
    for name, ver, lic, _repo, _t in rows:
        out.append(f"| {name} | {ver} | {lic.replace('|', '/')} |")
    out.append("\n## Licence texts\n")
    out.append("Each text below is the one shipped by the packages listed under it.\n")
    for n, (text, names) in enumerate(sorted(groups.values(), key=lambda g: g[1][0]), 1):
        out.append(f"### Text {n}\n")
        out.append("Used by: " + ", ".join(sorted(set(names))) + "\n")
        out.append("```text\n" + text.replace("```", "'''") + "\n```\n")
    if missing:
        out.append("## Packages that ship no licence file\n")
        out.append("The package's own manifest states the licence shown in the table above; the standard text of that licence applies.\n")
        out.append(", ".join(sorted(set(missing))) + "\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"{len(rows)} packages, {len(groups)} distinct licence texts, {len(missing)} without a licence file -> {OUT}")


if __name__ == "__main__":
    main()
