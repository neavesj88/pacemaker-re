"""Emit the device's SQLite DDL from an unstripped pmplayer (ELF32 ARM LE).

Columns come from the tl::g_*Fields symbols (arrays of {char* name, char* type}); table names
come from the descriptor that pairs a UTF-32 table name with each current-version array.
Versioned arrays (g_mixFieldsV4 etc.) are older schemas kept for migration and are emitted
as comments only.
"""
import re, struct, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from ptrtables import load, cstr, v2o

def wstr(d, segs, va):
    o, out = v2o(segs, va), []
    while o is not None and len(out) < 64:
        c, = struct.unpack_from("<I", d, o)
        if c == 0 or c > 0x10ffff:
            break
        out.append(chr(c)); o += 4
    s = "".join(out)
    return s if re.fullmatch(r"[a-z_][a-z0-9_]*", s) else None

def symbols(d):
    shoff, = struct.unpack_from("<I", d, 0x20); shent, shnum, _ = struct.unpack_from("<HHH", d, 0x2e)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shent) for i in range(shnum)]
    for s in secs:
        if s[1] not in (2, 11):
            continue
        st = secs[s[6]]
        for k in range(s[5] // 16):
            nm, val, size, _i, _o, _n = struct.unpack_from("<IIIBBH", d, s[4] + 16 * k)
            e = d.find(b"\0", st[4] + nm)
            yield d[st[4] + nm:e].decode(errors="replace"), val, size

def main(path):
    d, segs = load(path)
    arrays = {}
    for name, va, size in symbols(d):
        m = re.fullmatch(r"_ZN2tl\d+(g_\w+Fields\w*)E", name)
        if m and size:
            arrays[m.group(1)] = (va, size // 8)
    print(f"-- generated by scripts/gen-schema.py from {os.path.basename(path)}; do not edit by hand")
    for sym, (va, n) in sorted(arrays.items(), key=lambda kv: kv[1][0]):
        table = None
        needle = struct.pack("<I", va); i = d.find(needle)
        while i != -1 and table is None:
            if i % 4 == 0:
                table = wstr(d, segs, struct.unpack_from("<I", d, i - 4)[0])
            i = d.find(needle, i + 4)
        o = v2o(segs, va)
        cols = [(cstr(d, segs, struct.unpack_from("<I", d, o + 8 * k)[0]),
                 cstr(d, segs, struct.unpack_from("<I", d, o + 8 * k + 4)[0])) for k in range(n)]
        body = ",\n".join(f"  {c} {t}" for c, t in cols)
        if table:
            print(f"\n-- {sym}\nCREATE TABLE {table} (\n{body}\n);")
        else:
            print(f"\n-- {sym}: older schema revision used by migrations\n/*\n{body}\n*/")

if __name__ == "__main__":
    main(sys.argv[1])
